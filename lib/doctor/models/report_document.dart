import 'package:cloud_firestore/cloud_firestore.dart';

/// Clinical review status of an uploaded report document.
enum ReportReviewStatus {
  uploaded,
  reviewed;

  String get label {
    switch (this) {
      case ReportReviewStatus.uploaded:
        return 'Uploaded (Pending Review)';
      case ReportReviewStatus.reviewed:
        return 'Reviewed by Doctor';
    }
  }

  static ReportReviewStatus fromString(String? val) {
    if (val == null) return ReportReviewStatus.uploaded;
    final lower = val.toLowerCase().trim();
    if (lower == 'reviewed') {
      return ReportReviewStatus.reviewed;
    }
    return ReportReviewStatus.uploaded;
  }
}

/// Doctor review and approval status for an AI-generated report summary.
enum AiReportSummaryStatus {
  reviewRequired,
  approvedByDoctor;

  String get label {
    switch (this) {
      case AiReportSummaryStatus.reviewRequired:
        return 'REVIEW REQUIRED';
      case AiReportSummaryStatus.approvedByDoctor:
        return 'APPROVED_BY_DOCTOR';
    }
  }

  static AiReportSummaryStatus fromString(String? val) {
    if (val == null) return AiReportSummaryStatus.reviewRequired;
    final normalized = val.trim().toUpperCase();
    if (normalized == 'APPROVED_BY_DOCTOR' || normalized == 'APPROVED') {
      return AiReportSummaryStatus.approvedByDoctor;
    }
    return AiReportSummaryStatus.reviewRequired;
  }
}

/// Extracted diagnostic parameter measurement for laboratory reports.
class ReportMeasurement {
  final String parameter;
  final String value;
  final String unit;
  final String referenceRange;
  final String? flag;

  const ReportMeasurement({
    required this.parameter,
    required this.value,
    this.unit = '',
    this.referenceRange = '',
    this.flag,
  });

  Map<String, dynamic> toMap() => {
        'parameter': parameter,
        'value': value,
        if (unit.isNotEmpty) 'unit': unit,
        if (referenceRange.isNotEmpty) 'referenceRange': referenceRange,
        if (flag != null) 'flag': flag,
      };

  factory ReportMeasurement.fromMap(Map<String, dynamic> map) => ReportMeasurement(
        parameter: map['parameter'] as String? ?? '',
        value: map['value'] as String? ?? '',
        unit: map['unit'] as String? ?? '',
        referenceRange: map['referenceRange'] as String? ?? '',
        flag: map['flag'] as String?,
      );

  @override
  String toString() {
    final buffer = StringBuffer(parameter);
    buffer.write(' — $value');
    if (unit.isNotEmpty) buffer.write(' $unit');
    if (referenceRange.isNotEmpty) buffer.write(' (Ref: $referenceRange)');
    if (flag != null && flag!.isNotEmpty) buffer.write(' [$flag]');
    return buffer.toString();
  }
}

/// Structured clinical summary generated by the AI Medical Report Summarization Assistant.
///
/// Safety Rules:
/// - AI must NOT diagnose the patient.
/// - AI must NOT prescribe treatment.
/// - Summaries require explicit doctor verification and approval.
class AiReportSummaryRecord {
  final String summaryId;
  final String patientId;
  final String caseId;
  final String visitId;
  final String investigationId;
  final String reportId;
  final String fileName;
  final String investigationName;
  final String? reportDate;
  final String reportOverview;
  final List<String> keyFindings;
  final List<ReportMeasurement> reportedMeasurements;
  final List<String> reportedFindings;
  final String reportedImpression;
  final List<String> itemsToReview;
  final List<String> dataQualityOrUncertainty;
  final String rawSummaryText;
  final AiReportSummaryStatus status;
  final String? approvedByDoctorId;
  final DateTime? approvedAt;
  final DateTime generatedAt;
  final DateTime? updatedAt;

  const AiReportSummaryRecord({
    required this.summaryId,
    required this.patientId,
    required this.caseId,
    required this.visitId,
    required this.investigationId,
    required this.reportId,
    required this.fileName,
    required this.investigationName,
    this.reportDate,
    required this.reportOverview,
    this.keyFindings = const [],
    this.reportedMeasurements = const [],
    this.reportedFindings = const [],
    this.reportedImpression = '',
    this.itemsToReview = const [],
    this.dataQualityOrUncertainty = const [],
    this.rawSummaryText = '',
    this.status = AiReportSummaryStatus.reviewRequired,
    this.approvedByDoctorId,
    this.approvedAt,
    required this.generatedAt,
    this.updatedAt,
  });

  bool get isApproved => status == AiReportSummaryStatus.approvedByDoctor;
  bool get isReviewRequired => status == AiReportSummaryStatus.reviewRequired;

  AiReportSummaryRecord copyWith({
    String? summaryId,
    String? patientId,
    String? caseId,
    String? visitId,
    String? investigationId,
    String? reportId,
    String? fileName,
    String? investigationName,
    String? reportDate,
    String? reportOverview,
    List<String>? keyFindings,
    List<ReportMeasurement>? reportedMeasurements,
    List<String>? reportedFindings,
    String? reportedImpression,
    List<String>? itemsToReview,
    List<String>? dataQualityOrUncertainty,
    String? rawSummaryText,
    AiReportSummaryStatus? status,
    String? approvedByDoctorId,
    DateTime? approvedAt,
    DateTime? generatedAt,
    DateTime? updatedAt,
  }) {
    return AiReportSummaryRecord(
      summaryId: summaryId ?? this.summaryId,
      patientId: patientId ?? this.patientId,
      caseId: caseId ?? this.caseId,
      visitId: visitId ?? this.visitId,
      investigationId: investigationId ?? this.investigationId,
      reportId: reportId ?? this.reportId,
      fileName: fileName ?? this.fileName,
      investigationName: investigationName ?? this.investigationName,
      reportDate: reportDate ?? this.reportDate,
      reportOverview: reportOverview ?? this.reportOverview,
      keyFindings: keyFindings ?? this.keyFindings,
      reportedMeasurements: reportedMeasurements ?? this.reportedMeasurements,
      reportedFindings: reportedFindings ?? this.reportedFindings,
      reportedImpression: reportedImpression ?? this.reportedImpression,
      itemsToReview: itemsToReview ?? this.itemsToReview,
      dataQualityOrUncertainty:
          dataQualityOrUncertainty ?? this.dataQualityOrUncertainty,
      rawSummaryText: rawSummaryText ?? this.rawSummaryText,
      status: status ?? this.status,
      approvedByDoctorId: approvedByDoctorId ?? this.approvedByDoctorId,
      approvedAt: approvedAt ?? this.approvedAt,
      generatedAt: generatedAt ?? this.generatedAt,
      updatedAt: updatedAt ?? this.updatedAt,
    );
  }

  /// Formats the summary strictly according to the required 7-section clinical layout.
  String toFormattedDisplayString() {
    final buffer = StringBuffer();
    buffer.writeln('AI MEDICAL REPORT SUMMARY\n');
    buffer.writeln('Report:\n$fileName\n');
    buffer.writeln('Investigation:\n$investigationName\n');
    if (reportDate != null && reportDate!.isNotEmpty) {
      buffer.writeln('Report Date:\n$reportDate\n');
    }
    buffer.writeln('--------------------------------\n');
    buffer.writeln('1. REPORT OVERVIEW\n');
    buffer.writeln('$reportOverview\n');
    buffer.writeln('--------------------------------\n');
    buffer.writeln('2. KEY FINDINGS\n');
    if (keyFindings.isEmpty) {
      buffer.writeln('No specific abnormal findings explicitly noted.\n');
    } else {
      for (final f in keyFindings) {
        buffer.writeln('• $f');
      }
      buffer.writeln();
    }
    buffer.writeln('--------------------------------\n');
    buffer.writeln('3. REPORTED MEASUREMENTS\n');
    if (reportedMeasurements.isEmpty) {
      buffer.writeln('No numeric laboratory measurements present.\n');
    } else {
      for (final m in reportedMeasurements) {
        buffer.writeln('• $m');
      }
      buffer.writeln();
    }
    buffer.writeln('--------------------------------\n');
    buffer.writeln('4. REPORTED FINDINGS\n');
    if (reportedFindings.isEmpty) {
      buffer.writeln('No additional imaging or pathology findings reported.\n');
    } else {
      for (final rf in reportedFindings) {
        buffer.writeln('• $rf');
      }
      buffer.writeln();
    }
    buffer.writeln('--------------------------------\n');
    buffer.writeln('5. REPORTED IMPRESSION / CONCLUSION\n');
    buffer.writeln(reportedImpression.isNotEmpty
        ? '$reportedImpression\n'
        : 'No separate impression section reported.\n');
    buffer.writeln('--------------------------------\n');
    buffer.writeln('6. ITEMS TO REVIEW\n');
    if (itemsToReview.isEmpty) {
      buffer.writeln('No flagged review items.\n');
    } else {
      for (final r in itemsToReview) {
        buffer.writeln('• $r');
      }
      buffer.writeln();
    }
    buffer.writeln('--------------------------------\n');
    buffer.writeln('7. DATA QUALITY / UNCERTAINTY\n');
    if (dataQualityOrUncertainty.isEmpty) {
      buffer.writeln('None reported.\n');
    } else {
      for (final dq in dataQualityOrUncertainty) {
        buffer.writeln('• $dq');
      }
      buffer.writeln();
    }
    buffer.writeln('--------------------------------\n');
    buffer.writeln('AI-generated summary\nDoctor verification required.');
    return buffer.toString();
  }

  Map<String, dynamic> toMap() {
    return {
      'summaryId': summaryId,
      'patientId': patientId,
      'caseId': caseId,
      'visitId': visitId,
      'investigationId': investigationId,
      'reportId': reportId,
      'fileName': fileName,
      'investigationName': investigationName,
      if (reportDate != null) 'reportDate': reportDate,
      'reportOverview': reportOverview,
      'keyFindings': keyFindings,
      'reportedMeasurements':
          reportedMeasurements.map((m) => m.toMap()).toList(),
      'reportedFindings': reportedFindings,
      'reportedImpression': reportedImpression,
      'itemsToReview': itemsToReview,
      'dataQualityOrUncertainty': dataQualityOrUncertainty,
      'rawSummaryText': rawSummaryText.isNotEmpty
          ? rawSummaryText
          : toFormattedDisplayString(),
      'status': status.name,
      if (approvedByDoctorId != null) 'approvedByDoctorId': approvedByDoctorId,
      if (approvedAt != null) 'approvedAt': approvedAt!.toIso8601String(),
      'generatedAt': generatedAt.toIso8601String(),
      if (updatedAt != null) 'updatedAt': updatedAt!.toIso8601String(),
    };
  }

  factory AiReportSummaryRecord.fromMap(Map<String, dynamic> map) {
    DateTime parseDate(dynamic val) {
      if (val is Timestamp) return val.toDate();
      if (val is String) return DateTime.tryParse(val) ?? DateTime.now();
      if (val is int) return DateTime.fromMillisecondsSinceEpoch(val);
      return DateTime.now();
    }

    DateTime? parseOptionalDate(dynamic val) {
      if (val == null) return null;
      if (val is Timestamp) return val.toDate();
      if (val is String) return DateTime.tryParse(val);
      if (val is int) return DateTime.fromMillisecondsSinceEpoch(val);
      return null;
    }

    final measurementsRaw = map['reportedMeasurements'];
    final measurements = <ReportMeasurement>[];
    if (measurementsRaw is List) {
      for (final item in measurementsRaw) {
        if (item is Map<String, dynamic>) {
          measurements.add(ReportMeasurement.fromMap(item));
        } else if (item is Map) {
          measurements
              .add(ReportMeasurement.fromMap(Map<String, dynamic>.from(item)));
        }
      }
    }

    List<String> parseStringList(dynamic val) {
      if (val is List) {
        return val.map((e) => e.toString()).toList();
      }
      return const [];
    }

    return AiReportSummaryRecord(
      summaryId: map['summaryId'] as String? ?? '',
      patientId: map['patientId'] as String? ?? '',
      caseId: map['caseId'] as String? ?? '',
      visitId: map['visitId'] as String? ?? '',
      investigationId: map['investigationId'] as String? ?? '',
      reportId: map['reportId'] as String? ?? '',
      fileName: map['fileName'] as String? ?? '',
      investigationName: map['investigationName'] as String? ?? '',
      reportDate: map['reportDate'] as String?,
      reportOverview: map['reportOverview'] as String? ?? '',
      keyFindings: parseStringList(map['keyFindings']),
      reportedMeasurements: measurements,
      reportedFindings: parseStringList(map['reportedFindings']),
      reportedImpression: map['reportedImpression'] as String? ?? '',
      itemsToReview: parseStringList(map['itemsToReview']),
      dataQualityOrUncertainty:
          parseStringList(map['dataQualityOrUncertainty']),
      rawSummaryText: map['rawSummaryText'] as String? ?? '',
      status: AiReportSummaryStatus.fromString(map['status'] as String?),
      approvedByDoctorId: map['approvedByDoctorId'] as String?,
      approvedAt: parseOptionalDate(map['approvedAt']),
      generatedAt: parseDate(map['generatedAt']),
      updatedAt: parseOptionalDate(map['updatedAt']),
    );
  }
}

/// Model representing an uploaded patient medical diagnostic report document.
///
/// Hierarchy:
/// `patients/{patientId}/cases/{caseId}/visits/{visitId}/reports/{reportId}`
///
/// Storage path:
/// `patients/{patientId}/cases/{caseId}/visits/{visitId}/reports/{investigationId}/{fileName}`
class ReportDocument {
  final String reportId;
  final String patientId;
  final String caseId;
  final String visitId;
  final String investigationId;
  final String fileName;
  final String contentType;
  final int fileSizeBytes;
  final String storagePath;
  final String storageProvider;
  final String storageBucket;
  final DateTime uploadedAt;
  final String uploadedByPatientId;
  final ReportReviewStatus reviewStatus;
  final DateTime? reviewedAt;
  final String? reviewedByDoctorId;
  final String? downloadUrl;
  final String? notes;
  final DateTime? createdAt;
  final DateTime? updatedAt;
  final AiReportSummaryRecord? aiSummary;

  const ReportDocument({
    required this.reportId,
    required this.patientId,
    required this.caseId,
    required this.visitId,
    required this.investigationId,
    required this.fileName,
    required this.contentType,
    required this.fileSizeBytes,
    required this.storagePath,
    this.storageProvider = 'supabase',
    this.storageBucket = 'aayusathi-reports',
    required this.uploadedAt,
    required this.uploadedByPatientId,
    this.reviewStatus = ReportReviewStatus.uploaded,
    this.reviewedAt,
    this.reviewedByDoctorId,
    this.downloadUrl,
    this.notes,
    this.createdAt,
    this.updatedAt,
    this.aiSummary,
  });

  bool get isUploaded => reviewStatus == ReportReviewStatus.uploaded;
  bool get isReviewed => reviewStatus == ReportReviewStatus.reviewed;
  bool get isPdf => contentType.toLowerCase().contains('pdf');
  bool get isImage =>
      contentType.toLowerCase().contains('image') ||
      contentType.toLowerCase().contains('jpeg') ||
      contentType.toLowerCase().contains('jpg') ||
      contentType.toLowerCase().contains('png');
  bool get isOfficialVisitReport =>
      investigationId == 'OFFICIAL_VISIT_REPORT' ||
      reportId.startsWith('OFFICIAL-REPORT-');
  bool get isPatientUploadedReport => !isOfficialVisitReport;
  bool get hasAiSummary => aiSummary != null;
  bool get isAiSummaryApproved => aiSummary?.isApproved ?? false;

  ReportDocument copyWith({
    String? reportId,
    String? patientId,
    String? caseId,
    String? visitId,
    String? investigationId,
    String? fileName,
    String? contentType,
    int? fileSizeBytes,
    String? storagePath,
    String? storageProvider,
    String? storageBucket,
    DateTime? uploadedAt,
    String? uploadedByPatientId,
    ReportReviewStatus? reviewStatus,
    DateTime? reviewedAt,
    String? reviewedByDoctorId,
    String? downloadUrl,
    String? notes,
    DateTime? createdAt,
    DateTime? updatedAt,
    AiReportSummaryRecord? aiSummary,
  }) {
    return ReportDocument(
      reportId: reportId ?? this.reportId,
      patientId: patientId ?? this.patientId,
      caseId: caseId ?? this.caseId,
      visitId: visitId ?? this.visitId,
      investigationId: investigationId ?? this.investigationId,
      fileName: fileName ?? this.fileName,
      contentType: contentType ?? this.contentType,
      fileSizeBytes: fileSizeBytes ?? this.fileSizeBytes,
      storagePath: storagePath ?? this.storagePath,
      storageProvider: storageProvider ?? this.storageProvider,
      storageBucket: storageBucket ?? this.storageBucket,
      uploadedAt: uploadedAt ?? this.uploadedAt,
      uploadedByPatientId: uploadedByPatientId ?? this.uploadedByPatientId,
      reviewStatus: reviewStatus ?? this.reviewStatus,
      reviewedAt: reviewedAt ?? this.reviewedAt,
      reviewedByDoctorId: reviewedByDoctorId ?? this.reviewedByDoctorId,
      downloadUrl: downloadUrl ?? this.downloadUrl,
      notes: notes ?? this.notes,
      createdAt: createdAt ?? this.createdAt,
      updatedAt: updatedAt ?? this.updatedAt,
      aiSummary: aiSummary ?? this.aiSummary,
    );
  }

  Map<String, dynamic> toMap() {
    return {
      'reportId': reportId,
      'patientId': patientId,
      'caseId': caseId,
      'visitId': visitId,
      'investigationId': investigationId,
      'fileName': fileName,
      'contentType': contentType,
      'fileSizeBytes': fileSizeBytes,
      'storagePath': storagePath,
      'storageProvider': storageProvider,
      'storageBucket': storageBucket,
      'uploadedAt': uploadedAt.toIso8601String(),
      'uploadedByPatientId': uploadedByPatientId,
      'reviewStatus': reviewStatus.name,
      if (reviewedAt != null) 'reviewedAt': reviewedAt!.toIso8601String(),
      if (reviewedByDoctorId != null) 'reviewedByDoctorId': reviewedByDoctorId,
      if (downloadUrl != null) 'downloadUrl': downloadUrl,
      if (notes != null) 'notes': notes,
      if (createdAt != null) 'createdAt': createdAt!.toIso8601String(),
      if (updatedAt != null) 'updatedAt': updatedAt!.toIso8601String(),
      if (aiSummary != null) 'aiSummary': aiSummary!.toMap(),
    };
  }

  Map<String, dynamic> toFirestore() {
    return {
      'reportId': reportId,
      'patientId': patientId,
      'caseId': caseId,
      'visitId': visitId,
      'investigationId': investigationId,
      'fileName': fileName,
      'contentType': contentType,
      'fileSizeBytes': fileSizeBytes,
      'storagePath': storagePath,
      'storageProvider': storageProvider,
      'storageBucket': storageBucket,
      'uploadedAt': Timestamp.fromDate(uploadedAt),
      'uploadedByPatientId': uploadedByPatientId,
      'reviewStatus': reviewStatus.name,
      if (reviewedAt != null) 'reviewedAt': Timestamp.fromDate(reviewedAt!),
      if (reviewedByDoctorId != null) 'reviewedByDoctorId': reviewedByDoctorId,
      if (downloadUrl != null) 'downloadUrl': downloadUrl,
      if (notes != null) 'notes': notes,
      if (createdAt != null) 'createdAt': Timestamp.fromDate(createdAt!),
      if (updatedAt != null) 'updatedAt': Timestamp.fromDate(updatedAt!),
      if (aiSummary != null) 'aiSummary': aiSummary!.toMap(),
    };
  }

  factory ReportDocument.fromMap(Map<String, dynamic> map) {
    DateTime parseDate(dynamic val) {
      if (val is Timestamp) return val.toDate();
      if (val is String) return DateTime.tryParse(val) ?? DateTime.now();
      if (val is int) return DateTime.fromMillisecondsSinceEpoch(val);
      return DateTime.now();
    }

    DateTime? parseOptionalDate(dynamic val) {
      if (val == null) return null;
      if (val is Timestamp) return val.toDate();
      if (val is String) return DateTime.tryParse(val);
      if (val is int) return DateTime.fromMillisecondsSinceEpoch(val);
      return null;
    }

    AiReportSummaryRecord? parseSummary(dynamic val) {
      if (val is Map<String, dynamic>) {
        return AiReportSummaryRecord.fromMap(val);
      } else if (val is Map) {
        return AiReportSummaryRecord.fromMap(Map<String, dynamic>.from(val));
      }
      return null;
    }

    return ReportDocument(
      reportId: map['reportId'] as String? ?? '',
      patientId: map['patientId'] as String? ?? '',
      caseId: map['caseId'] as String? ?? '',
      visitId: map['visitId'] as String? ?? '',
      investigationId: map['investigationId'] as String? ?? '',
      fileName: map['fileName'] as String? ?? 'report.pdf',
      contentType: map['contentType'] as String? ?? 'application/pdf',
      fileSizeBytes: (map['fileSizeBytes'] as num?)?.toInt() ?? 0,
      storagePath: map['storagePath'] as String? ?? '',
      storageProvider: map['storageProvider'] as String? ?? 'supabase',
      storageBucket: map['storageBucket'] as String? ?? 'aayusathi-reports',
      uploadedAt: parseDate(map['uploadedAt']),
      uploadedByPatientId: map['uploadedByPatientId'] as String? ?? '',
      reviewStatus: ReportReviewStatus.fromString(map['reviewStatus'] as String?),
      reviewedAt: parseOptionalDate(map['reviewedAt']),
      reviewedByDoctorId: map['reviewedByDoctorId'] as String?,
      downloadUrl: map['downloadUrl'] as String?,
      notes: map['notes'] as String?,
      createdAt: parseOptionalDate(map['createdAt']) ?? parseOptionalDate(map['uploadedAt']),
      updatedAt: parseOptionalDate(map['updatedAt']) ?? parseOptionalDate(map['uploadedAt']),
      aiSummary: parseSummary(map['aiSummary']),
    );
  }

  factory ReportDocument.fromFirestore(
      Map<String, dynamic> data, [String? documentId]) {
    final map = Map<String, dynamic>.from(data);
    if (documentId != null && !map.containsKey('reportId')) {
      map['reportId'] = documentId;
    }
    return ReportDocument.fromMap(map);
  }

  @override
  String toString() =>
      'ReportDocument(id: $reportId, file: $fileName, provider: $storageProvider, bucket: $storageBucket, status: ${reviewStatus.name}, size: $fileSizeBytes)';
}
