import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/foundation.dart';
import 'package:flutter/widgets.dart';
import '../../firebase_options.dart';

/// Initialization status result for Firebase services.
class FirebaseInitResult {
  final bool isInitialized;
  final String? errorMessage;
  final dynamic error;

  const FirebaseInitResult({
    required this.isInitialized,
    this.errorMessage,
    this.error,
  });

  const FirebaseInitResult.success()
      : isInitialized = true,
        errorMessage = null,
        error = null;

  const FirebaseInitResult.failure(this.errorMessage, [this.error])
      : isInitialized = false;

  @override
  String toString() => isInitialized
      ? 'FirebaseInitResult(initialized: true)'
      : 'FirebaseInitResult(initialized: false, error: $errorMessage)';
}

/// Helper service responsible for safe, non-crashing Firebase initialization.
class FirebaseInitializer {
  FirebaseInitializer._();

  static bool _isInitialized = false;
  static FirebaseInitResult? _lastResult;

  static bool get isInitialized => _isInitialized;
  static FirebaseInitResult? get lastResult => _lastResult;

  /// Initializes Firebase using the pre-configured [DefaultFirebaseOptions].
  ///
  /// If Firebase fails to initialize (e.g. offline, missing native platform config,
  /// or unsupported environment), this method catches the exception and returns
  /// [FirebaseInitResult.failure] rather than letting the Flutter app crash.
  static Future<FirebaseInitResult> initialize() async {
    if (_isInitialized) {
      return const FirebaseInitResult.success();
    }

    try {
      WidgetsFlutterBinding.ensureInitialized();
      
      // DefaultFirebaseOptions is generated by FlutterFire CLI
      final options = DefaultFirebaseOptions.currentPlatform;
      await Firebase.initializeApp(options: options);

      _isInitialized = true;
      _lastResult = const FirebaseInitResult.success();
      debugPrint('[AAYUSATHI] Firebase initialized successfully with project: ${options.projectId}');
      return _lastResult!;
    } catch (e, stackTrace) {
      final errorMsg = e.toString();
      debugPrint('[AAYUSATHI WARNING] Firebase initialization failed: $errorMsg');
      debugPrint('[AAYUSATHI WARNING] Falling back safely to Mock backend mode.');
      if (kDebugMode) {
        debugPrint(stackTrace.toString());
      }
      _isInitialized = false;
      _lastResult = FirebaseInitResult.failure(errorMsg, e);
      return _lastResult!;
    }
  }
}
